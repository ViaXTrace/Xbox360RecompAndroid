static const uint8_t kRcon[11] = {
    0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36
};

// GF(2^8) multiplication
static inline uint8_t xtime(uint8_t a) { return (a << 1) ^ ((a & 0x80) ? 0x1b : 0); }
static inline uint8_t mul(uint8_t a, uint8_t b) {
    uint8_t r = 0;
    for (int i = 0; i < 8; i++) {
        if (b & 1) r ^= a;
        a = xtime(a);
        b >>= 1;
    }
    return r;
}

struct AesState {
    uint8_t s[4][4];
};

// Key expansion
static void keyExpand(const uint8_t* key, uint32_t* w) {
    for (int i = 0; i < 4; i++) {
        w[i] = (key[4*i]<<24)|(key[4*i+1]<<16)|(key[4*i+2]<<8)|key[4*i+3];
    }
    for (int i = 4; i < 44; i++) {
        uint32_t t = w[i-1];
        if (i % 4 == 0) {
            t = ((uint32_t)kSbox[(t>>16)&0xff]<<24) | ((uint32_t)kSbox[(t>>8)&0xff]<<16) |
                ((uint32_t)kSbox[t&0xff]<<8) | (uint32_t)kSbox[(t>>24)&0xff];
            t ^= (uint32_t)kRcon[i/4] << 24;
        }
        w[i] = w[i-4] ^ t;
    }
}

static void addRoundKey(AesState& s, const uint32_t* w, int round) {
    for (int c = 0; c < 4; c++) {
        uint32_t rk = w[round*4+c];
        s.s[0][c] ^= (rk>>24)&0xff;
        s.s[1][c] ^= (rk>>16)&0xff;
        s.s[2][c] ^= (rk>>8)&0xff;
        s.s[3][c] ^= rk&0xff;
    }
}

static void subBytes(AesState& s) {
    for (auto& row : s.s) for (auto& v : row) v = kSbox[v];
}

static void shiftRows(AesState& s) {
    uint8_t t;
    t=s.s[1][0]; s.s[1][0]=s.s[1][1]; s.s[1][1]=s.s[1][2]; s.s[1][2]=s.s[1][3]; s.s[1][3]=t;
    t=s.s[2][0]; s.s[2][0]=s.s[2][2]; s.s[2][2]=t; t=s.s[2][1]; s.s[2][1]=s.s[2][3]; s.s[2][3]=t;
    t=s.s[3][3]; s.s[3][3]=s.s[3][2]; s.s[3][2]=s.s[3][1]; s.s[3][1]=s.s[3][0]; s.s[3][0]=t;
}

static void mixColumns(AesState& s) {
    for (int c = 0; c < 4; c++) {
        uint8_t s0=s.s[0][c],s1=s.s[1][c],s2=s.s[2][c],s3=s.s[3][c];
        s.s[0][c]=mul(s0,2)^mul(s1,3)^s2^s3;
        s.s[1][c]=s0^mul(s1,2)^mul(s2,3)^s3;
        s.s[2][c]=s0^s1^mul(s2,2)^mul(s3,3);
        s.s[3][c]=mul(s0,3)^s1^s2^mul(s3,2);
    }
}

static void subBytesInv(AesState& s) {
    for (auto& row : s.s) for (auto& v : row) v = kSboxInv[v];
}

static void shiftRowsInv(AesState& s) {
    uint8_t t;
    t=s.s[1][3]; s.s[1][3]=s.s[1][2]; s.s[1][2]=s.s[1][1]; s.s[1][1]=s.s[1][0]; s.s[1][0]=t;
    t=s.s[2][0]; s.s[2][0]=s.s[2][2]; s.s[2][2]=t; t=s.s[2][1]; s.s[2][1]=s.s[2][3]; s.s[2][3]=t;
    t=s.s[3][0]; s.s[3][0]=s.s[3][1]; s.s[3][1]=s.s[3][2]; s.s[3][2]=s.s[3][3]; s.s[3][3]=t;
}

static void mixColumnsInv(AesState& s) {
    for (int c = 0; c < 4; c++) {
        uint8_t s0=s.s[0][c],s1=s.s[1][c],s2=s.s[2][c],s3=s.s[3][c];
        s.s[0][c]=mul(s0,0x0e)^mul(s1,0x0b)^mul(s2,0x0d)^mul(s3,0x09);
        s.s[1][c]=mul(s0,0x09)^mul(s1,0x0e)^mul(s2,0x0b)^mul(s3,0x0d);
        s.s[2][c]=mul(s0,0x0d)^mul(s1,0x09)^mul(s2,0x0e)^mul(s3,0x0b);
        s.s[3][c]=mul(s0,0x0b)^mul(s1,0x0d)^mul(s2,0x09)^mul(s3,0x0e);
    }
}

static void stateFromBlock(AesState& st, const uint8_t* block) {
    for (int r=0;r<4;r++) for (int c=0;c<4;c++) st.s[r][c]=block[r+4*c];
}

static void stateToBlock(const AesState& st, uint8_t* block) {
    for (int r=0;r<4;r++) for (int c=0;c<4;c++) block[r+4*c]=st.s[r][c];
}

static void aesEncryptBlock(const uint32_t* rk, const uint8_t* in, uint8_t* out) {
    AesState st;
    stateFromBlock(st, in);
    addRoundKey(st, rk, 0);
    for (int r = 1; r < 10; r++) {
        subBytes(st); shiftRows(st); mixColumns(st); addRoundKey(st, rk, r);
    }
    subBytes(st); shiftRows(st); addRoundKey(st, rk, 10);
    stateToBlock(st, out);
}

static void aesDecryptBlock(const uint32_t* rk, const uint8_t* in, uint8_t* out) {
    AesState st;
    stateFromBlock(st, in);
    addRoundKey(st, rk, 10);
    for (int r = 9; r >= 1; r--) {
        shiftRowsInv(st); subBytesInv(st); addRoundKey(st, rk, r); mixColumnsInv(st);
    }
    shiftRowsInv(st); subBytesInv(st); addRoundKey(st, rk, 0);
    stateToBlock(st, out);
}

void Aes128::ecbEncrypt(const uint8_t* key16, const uint8_t* in, uint8_t* out) {
    uint32_t rk[44];
    keyExpand(key16, rk);
    aesEncryptBlock(rk, in, out);
}

void Aes128::ecbDecrypt(const uint8_t* key16, const uint8_t* in, uint8_t* out) {
    uint32_t rk[44];
    keyExpand(key16, rk);
    aesDecryptBlock(rk, in, out);
}

void Aes128::cbcDecrypt(const uint8_t* key16, uint8_t* iv16,
                        uint8_t* data, size_t len) {
    uint32_t rk[44];
    keyExpand(key16, rk);
    uint8_t prev[16];
    memcpy(prev, iv16, 16);
    for (size_t i = 0; i + 16 <= len; i += 16) {
        uint8_t* blk = data + i;
        uint8_t tmp[16];
        memcpy(tmp, blk, 16);
        aesDecryptBlock(rk, blk, blk);
        for (int j = 0; j < 16; j++) blk[j] ^= prev[j];
        memcpy(prev, tmp, 16);
    }
    memcpy(iv16, prev, 16);
}

void Aes128::cbcEncrypt(const uint8_t* key16, uint8_t* iv16,
                        uint8_t* data, size_t len) {
    uint32_t rk[44];
    keyExpand(key16, rk);
    for (size_t i = 0; i + 16 <= len; i += 16) {
        uint8_t* blk = data + i;
        for (int j = 0; j < 16; j++) blk[j] ^= iv16[j];
        aesEncryptBlock(rk, blk, blk);
        memcpy(iv16, blk, 16);
    }
}

